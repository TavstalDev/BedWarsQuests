package io.github.tavstaldev.bedWarsQuests.models;

/**
 * The ECompletionKind enum represents the different kinds of completion
 * types for achievements or objectives in the BedWarsQuests plugin.
 */
public enum ECompletionKind {
    /** Represents the completion of an achievement. */
    Achievement,

    /** Represents the completion of a daily objective. */
    DailyObjective,

    /** Represents the completion of a weekly objective. */
    WeeklyObjective
}
